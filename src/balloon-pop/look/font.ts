/** Each glyph as horizontal runs [row, column, length], so drawing a run is one fillRect. */
export const GLYPHS = new Map<string, [number, number, number][]>();
for (const [ch, src] of Object.entries(SOURCE)) {
  const runs: [number, number, number][] = [];
  src.split("|").forEach((line, row) => {
    for (let col = 0; col < line.length; col++) {
      if (line[col] !== "#") continue;
      const start = col;
      while (line[col + 1] === "#") col++;
      runs.push([row, start, col - start + 1]);
    }
  });
  GLYPHS.set(ch, runs);
}

export function glyphFor(ch: string): [number, number, number][] | undefined {
  return GLYPHS.get(ch.toUpperCase());
}

export function textWidth(s: string, scale = 1): number {
  return s.length === 0 ? 0 : (s.length * ADVANCE - 1) * scale;
}
